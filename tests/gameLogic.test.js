const assert = require('node:assert/strict');
const Game = require('../server/gameLogic');
const game = new Game();
const players = ['a','b','c','d'].map(name => ({name}));
game.startGame(players);
assert.equal(game.playerTiles.map(a => a.length).reduce((a,b) => a+b), 85);
assert.equal(game.tiles.length, 20, '106 stones minus indicator and distributed 85 = 20');
assert.equal(game.playerTiles[game.currentPlayer].length, 22);
assert.equal(new Set([...game.tiles, game.indicator, ...game.playerTiles.flat()].map(t => t.id)).size, 106);
const normalColor = game.okey.color === 'Kirmizi' ? 'Mavi' : 'Kirmizi';
const setNum = game.okey.number === 7 ? 6 : 7;
const tile = (n, color=normalColor) => ({id:`${color}-${n}-x`,color,number:n,isJoker:false,isFakeJoker:false});
assert(game.isValidSequence([tile(4),tile(5),tile(6)]));
assert(!game.isValidSequence([tile(12),tile(13),tile(1)]));
assert(!game.isValidSequence([tile(12),tile(12),tile(13)]));
assert(game.isValidSet([tile(setNum,'Mavi'),tile(setNum,'Kirmizi'),tile(setNum,'Siyah')]));
assert(!game.isValidSet([tile(setNum,'Mavi'),tile(setNum,'Mavi'),tile(setNum,'Siyah')]));
assert.equal(game.calculateGroupValue([tile(4),tile(5),tile(6)]),15);
assert.equal(game.calculateGroupValue([tile(setNum,'Mavi'),tile(setNum,'Kirmizi'),tile(setNum,'Siyah')]),setNum * 3);
const jok = {id:'joker',color:game.okey.color, number:game.okey.number, isFakeJoker:false};
assert(game.isValidSequence([tile(4),jok,tile(6)]));
assert.equal(game.calculateGroupValue([tile(4),jok,tile(6)]), 15);
console.log('gameLogic: all 12 rule assertions passed');
